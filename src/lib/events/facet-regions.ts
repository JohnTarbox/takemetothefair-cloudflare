/**
 * OPE-395 — region definitions for the crawlable facet mesh.
 *
 * ── Why regions key on CITY ─────────────────────────────────────────────────
 * Measured against prod for MA + CT upcoming events before choosing:
 *
 *   venue attached  100%   city  100%   lat/lng  97%   zip  76%
 *
 * City is the only geographic field that is complete, and it is the one people
 * actually type — "fairs in the Berkshires", not "fairs in 01201". A ZIP-prefix
 * scheme would have been self-maintaining but silently drops a quarter of the
 * inventory; a lat/lng bounding box is both incomplete and wrong along borders,
 * where New England towns are small and adjacent regions interleave.
 *
 * ── The failure mode is ABSENCE, never a wrong claim ────────────────────────
 * An unmapped town simply does not appear on a region page. It still appears on
 * the state page and on the month and type facets, so nothing is lost from the
 * index — the event is only missing from one of four ways in. That is the right
 * direction to fail: a region page that omits a fair is incomplete, while one
 * that files Pittsfield under Cape Cod is wrong, and wrong is unrecoverable
 * because a reader who is misled once does not come back.
 *
 * Because absence is silent, `facetRegionCoverage()` measures the mapped share
 * of each state's inventory and a unit test fails if it decays. Drift here
 * shows up as a quietly shrinking region page, which nothing else would catch.
 *
 * ── Maintenance ─────────────────────────────────────────────────────────────
 * These lists cover every town currently hosting an upcoming event plus the
 * larger towns in each region that plausibly will. Municipalities essentially
 * never change, so this is a stable list rather than a moving target: adding a
 * town is a one-line edit, and forgetting to costs one region listing, not
 * correctness.
 *
 * Keep any single region under ~70 towns. The region predicate binds one SQL
 * parameter per town and D1 caps a statement at 100 bound parameters (see
 * `feedback_d1_batch_param_limit`), so a runaway list would throw at query time
 * rather than degrade. `facet-registry.test.ts` asserts the ceiling.
 */

export interface RegionDef {
  /** Display label, used in the H1, <title> and nav. */
  label: string;
  /**
   * A short geographic gloss, shown under the H1. Deliberately about WHERE the
   * region is and nothing else — no claim about any event's hours, price or
   * admission, per the same grounding rule as OPE-394.
   */
  blurb: string;
  /** Lowercased town names, matched against `lower(trim(venues.city))`. */
  cities: readonly string[];
}

