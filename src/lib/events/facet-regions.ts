/** Region slugs defined for a state, in declaration order. */
export function regionSlugsFor(stateSlug: string): string[] {
  return Object.keys(STATE_REGIONS[stateSlug] ?? {});
}

/** One region definition, or null when the state or slug is unknown. */
export function findRegion(stateSlug: string, regionSlug: string): RegionDef | null {
  return STATE_REGIONS[stateSlug]?.[regionSlug] ?? null;
}
