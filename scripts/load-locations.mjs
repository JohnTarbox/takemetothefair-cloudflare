#!/usr/bin/env node
/**
 * OPE-425 — load `data/ne-locations.tsv` into D1, seed aliases from the venue
 * data we already hold, and report what did not resolve.
 *
 * Emits SQL to stdout by default so the statements can be reviewed before they
 * touch production. Pipe it into wrangler to apply:
 *
 *   node scripts/load-locations.mjs > /tmp/locations.sql
 *   npx wrangler d1 execute takemetothefair-db --remote --file /tmp/locations.sql
 *
 * ── Discipline (docs/bulk-mutation-discipline.md) ────────────────────────
 *
 * Single-writer: this script. Idempotent: every statement is INSERT OR REPLACE
 * on a natural key (the Census GEOID for locations, state+alias for aliases),
 * so a re-run after a Census vintage bump updates in place and never
 * duplicates. Read-back verified: the counts to check are printed to stderr.
 * Rollback: the tables are new and additive; `venues.location_id` is nullable
 * and nothing reads it yet.
 *
 * ── What it deliberately does NOT do ─────────────────────────────────────
 *
 * It does not invent a parent for a village, and it does not guess a match for
 * a venue city it cannot resolve exactly. The unresolved remainder is the
 * OPE-421 report, and a fuzzy match here would quietly convert that report into
 * a set of wrong answers — the same failure mode as the hand-assembled list
 * this whole table exists to replace.
 */

import { readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TSV = resolve(ROOT, "data/ne-locations.tsv");

const q = (v) => (v === null || v === undefined || v === "" ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined || v === "" ? "NULL" : String(Number(v)));

/**
 * Normalize a place name for matching: lowercase, strip apostrophes and dots,
 * collapse whitespace. Deliberately conservative — anything looser stops being
 * a match and starts being a guess.
 *
 * WARNING: it must be expressible in SQLite, because the venue backfill runs as
 * an UPDATE and BOTH sides have to normalize identically. An earlier version of
 * this script normalized richly in JS (accent folding, St. -> Saint) and
 * matched with a cruder SQL expression, so the two sides disagreed and the
 * backfill would have silently under-matched — a failure that reads as "our
 * venue data is messy" rather than "our join is wrong". `SQL_NORMALIZE_CITY`
 * below is the same transform; the pair must be changed together.
 */
export function normalizePlace(s) {
  return (s || "")
    .toLowerCase()
    .replace(/['’.]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/** The SQLite twin of `normalizePlace`, applied to `venues.city`. */
const SQL_NORMALIZE_CITY =
  "trim(lower(replace(replace(replace(venues.city, '.', ''), char(39), ''), char(8217), '')))";

/**
 * Spelling variants worth storing as their own alias rows.
 *
 * Only the ones our own data actually produces: Saint/St. is the live case —
 * venues hold both "St. Albans" and "Saint Albans" for the same Vermont city.
 * A fixed, auditable list rather than a fuzzy matcher, so a wrong resolution is
 * impossible by construction: a variant either exists, or the venue lands in
 * the OPE-421 report where a human can look at it.
 */
function aliasVariants(name) {
  const base = normalizePlace(name);
  const out = new Set([base]);
  if (base.startsWith("saint ")) out.add("st " + base.slice(6));
  if (base.startsWith("st ")) out.add("saint " + base.slice(3));
  return [...out];
}

function readTsv(path) {
  const lines = readFileSync(path, "utf8").split(/\r?\n/).filter((l) => l.length > 0);
  const header = lines[0].split("\t");
  return lines.slice(1).map((line) => {
    const cells = line.split("\t");
    const row = {};
    header.forEach((h, i) => (row[h] = cells[i] ?? ""));
    return row;
  });
}

const rows = readTsv(TSV);
const out = [];

out.push("-- OPE-425 locations seed. Generated by scripts/load-locations.mjs.");
out.push("-- Idempotent: INSERT OR REPLACE on the Census GEOID.");
for (const r of rows) {
  out.push(
    `INSERT OR REPLACE INTO locations (id,state,county,county_note,county_vintage,name,type,parent_location_id,population,population_year,latitude,longitude,canonical_slug,source,is_denominator_eligible,last_verified_at) VALUES (` +
      [
        q(r.geoid),
        q(r.state),
        q(r.county),
        q(r.county_note),
        q(r.county_vintage),
        q(r.name),
        q(r.type),
        q(r.parent_geoid),
        n(r.population),
        n(r.population_year),
        n(r.latitude),
        n(r.longitude),
        q(r.canonical_slug),
        q(r.source),
        // OPE-425 finding 3 — a CDP's population is a SUBSET of its parent
        // municipality's, so it must never enter a SUM(population).
        r.type === "village_cdp" ? "0" : "1",
        "unixepoch()",
      ].join(",") +
      ");"
  );
}

// Aliases for the legal names that nobody writes — MA's "Winthrop Town",
// "Barnstable Town" and the rest. The seed stores the usable name; this keeps
// the legal form resolvable too.
out.push("");
out.push("-- Legal-name aliases (MA 'X Town' cities).");
for (const r of rows) {
  if (r.type !== "city" || !/^(MA)$/.test(r.state)) continue;
  const legal = `${r.name} Town`;
  out.push(
    `INSERT OR IGNORE INTO location_aliases (id,location_id,alias,state,alias_type,created_at) VALUES (` +
      [
        q(`alias-legal-${r.geoid}`),
        q(r.geoid),
        q(normalizePlace(legal)),
        q(r.state),
        q("historic"),
        "unixepoch()",
      ].join(",") +
      ");"
  );
}

// Every canonical name is its own alias, so the venue backfill is a single
// join against one table rather than a two-branch lookup.
out.push("");
out.push("-- Canonical names (and their Saint/St. variants) as aliases, so the");
out.push("-- backfill is one join against one table.");
for (const r of rows) {
  aliasVariants(r.name).forEach((alias, i) => {
    out.push(
      `INSERT OR IGNORE INTO location_aliases (id,location_id,alias,state,alias_type,created_at) VALUES (` +
        [
          q(`alias-canon-${r.geoid}-${i}`),
          q(r.geoid),
          q(alias),
          q(r.state),
          q(r.type === "village_cdp" ? "village" : i === 0 ? "postal" : "abbreviation"),
          "unixepoch()",
        ].join(",") +
        ");"
    );
  });
}

// Hand-verified aliases for names the Census place file does not carry
// (Oquossoc, Hyannis, and the postal/village names our submitters actually
// type). Small, auditable, one judgement per line — see the header of
// data/ne-location-aliases.tsv for why this file is hand-written when the
// universe file must not be.
const aliasRows = readFileSync(resolve(ROOT, "data/ne-location-aliases.tsv"), "utf8")
  .split(/\r?\n/)
  .filter((l) => l.length > 0 && !l.startsWith("#"))
  .slice(1)
  .map((l) => {
    const [state, alias, canonical_slug, alias_type, note] = l.split("\t");
    return { state, alias, canonical_slug, alias_type, note };
  })
  .filter((r) => r.state && r.alias && r.canonical_slug);

const slugToGeoid = new Map(rows.map((r) => [r.canonical_slug, r.geoid]));
out.push("");
out.push("-- Hand-verified aliases (data/ne-location-aliases.tsv).");
for (const a of aliasRows) {
  const geoid = slugToGeoid.get(a.canonical_slug);
  if (!geoid) {
    // Refuse to emit an alias pointing at nothing. A dangling target would
    // fail the FK at load time on a good day and resolve to NULL on a bad one.
    process.stderr.write(
      `WARNING: alias "${a.alias}" targets unknown slug "${a.canonical_slug}" — skipped\n`
    );
    continue;
  }
  out.push(
    `INSERT OR REPLACE INTO location_aliases (id,location_id,alias,state,alias_type,created_at) VALUES (` +
      [
        q(`alias-manual-${a.state}-${normalizePlace(a.alias).replace(/ /g, "-")}`),
        q(geoid),
        q(normalizePlace(a.alias)),
        q(a.state),
        q(a.alias_type),
        "unixepoch()",
      ].join(",") +
      ");"
  );
}

// The backfill. Exact normalized match only — see the docblock on why a fuzzy
// match here would turn the OPE-421 report into a set of confident wrong
// answers.
out.push("");
out.push("-- Pass 1 — backfill venues.location_id by exact normalized alias match.");
out.push(`UPDATE venues SET
  location_id = (
    SELECT a.location_id FROM location_aliases a
     WHERE a.state = venues.state
       AND a.alias = ${SQL_NORMALIZE_CITY}
     LIMIT 1
  ),
  location_matched_by = 'alias'
WHERE location_id IS NULL
  AND EXISTS (
    SELECT 1 FROM location_aliases a
     WHERE a.state = venues.state
       AND a.alias = ${SQL_NORMALIZE_CITY}
  );`);

// OPE-425 review finding 2 — the coordinate fallback.
//
// Pass 1 matches on the city STRING, so its residual conflated two different
// things: a venue whose city is genuinely junk, and a venue whose string just
// did not join. `MA | Cape Cod` was offered as proof the report worked — and it
// carries coordinates that land in Barnstable County. The venue is physically
// somewhere; only the string is broken.
//
// So: for a venue we could not name-match but CAN locate, resolve it to the
// nearest DENOMINATOR-ELIGIBLE municipality centroid in the same state, within
// a bounded radius, and record that the point (not the name) did the work.
//
// Bounded on purpose. Without the cap this assigns every stray coordinate to
// *something*, which is how a join limitation becomes a set of confident wrong
// answers — the failure this loader's docblock already refuses elsewhere.
//
// The longitude term is scaled by cos²(43°) ≈ 0.535 so a degree of longitude is
// not treated as a degree of latitude at New England's latitude. This is a
// nearest-CENTROID match, not point-in-polygon: the Bureau publishes no
// boundary file we can join in SQLite, and a centroid within ~25 km is an
// honest approximation PROVIDED it is labelled as one — which is what
// `location_matched_by = 'coordinates'` is for.
out.push("");
out.push("-- Pass 2 — coordinate fallback for venues pass 1 could not name-match.");
out.push(`UPDATE venues SET
  location_id = (
    SELECT l.id FROM locations l
     WHERE l.state = venues.state
       AND l.is_denominator_eligible = 1
       AND l.latitude IS NOT NULL AND l.longitude IS NOT NULL
     ORDER BY ((l.latitude - venues.latitude) * (l.latitude - venues.latitude))
            + ((l.longitude - venues.longitude) * (l.longitude - venues.longitude) * 0.535)
     LIMIT 1
  ),
  location_matched_by = 'coordinates'
WHERE location_id IS NULL
  AND latitude IS NOT NULL AND longitude IS NOT NULL
  AND (
    SELECT ((l.latitude - venues.latitude) * (l.latitude - venues.latitude))
         + ((l.longitude - venues.longitude) * (l.longitude - venues.longitude) * 0.535)
      FROM locations l
     WHERE l.state = venues.state
       AND l.is_denominator_eligible = 1
       AND l.latitude IS NOT NULL AND l.longitude IS NOT NULL
     ORDER BY 1 LIMIT 1
  ) < 0.0625;`);

process.stdout.write(out.join("\n") + "\n");

// Read-back checks go to stderr so they never pollute the SQL.
const byType = rows.reduce((acc, r) => ((acc[r.type] = (acc[r.type] ?? 0) + 1), acc), {});
process.stderr.write(
  `locations: ${rows.length} rows\n` +
    Object.entries(byType)
      .sort((a, b) => b[1] - a[1])
      .map(([t, c]) => `  ${t}: ${c}`)
      .join("\n") +
    `\n\nAfter applying, verify:\n` +
    `  SELECT COUNT(*) FROM locations;                          -- expect ${rows.length}\n` +
    `  SELECT COUNT(*) FROM venues WHERE location_id IS NOT NULL;\n` +
    `  SELECT state, city FROM venues WHERE location_id IS NULL AND city <> '';  -- the OPE-421 report\n`
);
