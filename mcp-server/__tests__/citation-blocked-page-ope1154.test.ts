/**
 * OPE-1154 — a page we could not read is not a source.
 *
 * Specimen: event b52c6acf, 2026-09-22. The registration link returned
 * CloudFront's 403 page; six citations were still written against that URL
 * with the 403 as their excerpt (so `source_verifiable` derived TRUE), while
 * the values came from the email body.
 */
import { describe, it, expect, beforeEach, vi } from "vitest";
import { createTestDb, type TestDb } from "./setup-db.js";
import { recordSourceCitations } from "../src/email-handlers/pipeline-citations.js";
import { eventDataCitations, events, promoters } from "../src/schema.js";
import { eq } from "drizzle-orm";

let db: TestDb;

beforeEach(() => {
  ({ db } = createTestDb());
  vi.spyOn(console, "warn").mockImplementation(() => {});
  db.insert(promoters)
    .values({ id: "promoter-1", companyName: "Test Promoter", slug: "test-promoter" })
    .run();
  db.insert(events)
    .values({
      id: "event-1",
      name: "VCS Holiday Market",
      slug: "vcs-holiday-market",
      promoterId: "promoter-1",
      status: "PENDING",
    })
    .run();
});

const URL_ = "https://holiday-market-vendor-registration-49978.cheddarup.com/";
const extracted = {
  url: URL_,
  event: {
    name: "VCS Holiday Market",
    startDate: "2026-12-05",
    endDate: "2026-12-05",
    startTime: "07:00",
    estimatedAttendance: 50,
    applicationDeadline: "2026-09-24",
  },
};
const rows = () =>
  db.select().from(eventDataCitations).where(eq(eventDataCitations.eventId, "event-1")).all();

describe("OPE-1154 — no citation from a blocked page", () => {
  it("writes nothing when the snapshot is CloudFront's 403", async () => {
    const res = await recordSourceCitations(db, {
      eventId: "event-1",
      extracted,
      source: { kind: "url", url: URL_ },
      fromAddress: "organizer@example.org",
      snapshot: {
        title: "ERROR: The request could not be satisfied",
        text: "403 ERROR The request could not be satisfied. Request blocked. Generated by cloudfront (CloudFront)",
        fetchedAt: new Date("2026-09-22T22:32:52Z"),
      },
    });
    expect(res).toEqual({ inserted: 0, reason: "blocked-page" });
    expect(rows()).toHaveLength(0);
  });

  it("landmark: the same extraction from a REAL page is cited", async () => {
    const res = await recordSourceCitations(db, {
      eventId: "event-1",
      extracted,
      source: { kind: "url", url: URL_ },
      fromAddress: "organizer@example.org",
      snapshot: {
        title: "VCS Holiday Market — Vendor Registration",
        text: "Saturday, December 5, 2026. Doors open 9 AM.",
        fetchedAt: new Date("2026-09-22T22:32:52Z"),
      },
    });
    expect(res.inserted).toBeGreaterThan(0);
    expect(rows().length).toBe(res.inserted);
  });

  it("the email body is still cited as the email", async () => {
    const res = await recordSourceCitations(db, {
      eventId: "event-1",
      extracted: { ...extracted, url: "" },
      source: { kind: "body" },
      fromAddress: "organizer@example.org",
    });
    expect(res.inserted).toBeGreaterThan(0);
    expect(new Set(rows().map((r) => r.sourceUrl))).toEqual(
      new Set(["email://organizer@example.org"])
    );
  });
});
